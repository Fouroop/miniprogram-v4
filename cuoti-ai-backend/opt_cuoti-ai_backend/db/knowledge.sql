-- ============================================================
-- 知识点大纲 + 用户掌握记录
-- 库：cuoti_ai
-- 执行：mysql -uroot -p cuoti_ai < knowledge.sql
-- ============================================================

CREATE TABLE IF NOT EXISTS knowledge_points (
  id INT PRIMARY KEY AUTO_INCREMENT,
  subject VARCHAR(32) NOT NULL,
  name VARCHAR(128) NOT NULL,
  parent_id INT NOT NULL DEFAULT 0,   -- 0=科目根；>0=所属章节
  level TINYINT NOT NULL DEFAULT 1,   -- 1=章节 2=知识点
  sort INT NOT NULL DEFAULT 0,
  INDEX idx_kp_subject (subject),
  INDEX idx_kp_parent (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user_knowledge (
  id INT PRIMARY KEY AUTO_INCREMENT,
  user_id INT NOT NULL,
  kp_id INT NOT NULL,
  level VARCHAR(16) NOT NULL DEFAULT 'weak',  -- weak/reviewing/mastered
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_user_kp (user_id, kp_id),
  INDEX idx_uk_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

